export const EN_STRINGS: Strings = en;

// --- locale-independent identity for a catalogue string ----------------------
//
// Collapsible sections persist their open / pinned / favourited state under a
// stable identifier, never a hash of the *rendered title*: a title hash changes
// every key when the language switches, silently resetting the whole layout, and
// two sections that share a title in different panels would fight over one key.
//
// Both dictionaries are structurally identical, so the dot-path of a value
// (`layoutPanel.timeSection`) is a stable, language-free identifier for it. Index
// every leaf of both locales once and hand that path out; call sites that use the
// same key twice (same title in two panels) must still pass an explicit `id`.
const titlePaths = new Map<string, string>();

function indexPath(value: unknown, path: string): void {
  if (typeof value === 'string') {
    if (!titlePaths.has(value)) titlePaths.set(value, path);
    return;
  }
  if (value && typeof value === 'object' && !Array.isArray(value)) {
    for (const [k, v] of Object.entries(value as Record<string, unknown>)) {
      indexPath(v, path ? `${path}.${k}` : k);
    }
  }
}
// `en` is typed against `zh`, so indexing either one is enough — but indexing
// both means a string that only ever appears in one locale still resolves.
indexPath(zh, '');
indexPath(en, '');

/** Language-independent identifier for a rendered UI string (falls back to a hash). */
export function titleKey(title: string): string {
  const path = titlePaths.get(title);
  if (path) return path;
  let h = 0;
  for (let i = 0; i < title.length; i += 1) h = ((h << 5) - h + title.charCodeAt(i)) | 0;
  return `raw:${Math.abs(h).toString(36)}`;
}

// --- active locale -----------------------------------------------------------
// `S` is re-assigned by setLanguage(). ES-module live bindings mean every
// importer sees the new dictionary immediately; the app additionally remounts
// on language change so memoised subtrees pick up the new strings too.

